package main

import (
	"net/http"
	"net/http/httptest"
	"strings"
	"testing"
	"time"

	"github.com/gorilla/websocket"
)

func TestJSONChat(t *testing.T) {
	h := &Hub{
		clients:    make(map[*Client]struct{}),
		register:   make(chan *Client),
		unregister: make(chan *Client),
		broadcast:  make(chan Message, 256),
	}
	go h.run()
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		serveWs(h, w, r)
	}))
	defer server.Close()
	started := time.Now().UTC()

	dial := func() *websocket.Conn {
		t.Helper()
		conn, _, err := websocket.DefaultDialer.Dial("ws"+strings.TrimPrefix(server.URL, "http"), nil)
		if err != nil {
			t.Fatal(err)
		}
		t.Cleanup(func() { conn.Close() })
		return conn
	}
	write := func(conn *websocket.Conn, kind int, data string) {
		t.Helper()
		if err := conn.SetWriteDeadline(time.Now().Add(3 * time.Second)); err != nil {
			t.Fatal(err)
		}
		if err := conn.WriteMessage(kind, []byte(data)); err != nil {
			t.Fatal(err)
		}
	}
	read := func(conn *websocket.Conn, content string) Message {
		t.Helper()
		if err := conn.SetReadDeadline(time.Now().Add(3 * time.Second)); err != nil {
			t.Fatal(err)
		}
		var msg Message
		if err := conn.ReadJSON(&msg); err != nil {
			t.Fatal(err)
		}
		if msg.Type != "chat" || msg.Content != content || msg.Sender == "" {
			t.Fatalf("unexpected message: %+v", msg)
		}
		if msg.Timestamp.Before(started) || msg.Timestamp.After(time.Now()) {
			t.Fatalf("timestamp was not generated by server: %v", msg.Timestamp)
		}
		return msg
	}

	first := dial()
	write(first, websocket.TextMessage, `{"type":"chat","content":"first ready"}`)
	firstID := read(first, "first ready").Sender
	second := dial()
	write(second, websocket.TextMessage, `{"type":"chat","content":"你好","sender":"forged","timestamp":"2000-01-01T00:00:00Z"}`)
	fromFirst := read(first, "你好")
	fromSecond := read(second, "你好")
	if fromFirst != fromSecond {
		t.Fatalf("clients received different broadcasts: %+v, %+v", fromFirst, fromSecond)
	}
	if fromFirst.Sender == "forged" || fromFirst.Sender == firstID {
		t.Fatalf("sender is not the second connection's ID: %q", fromFirst.Sender)
	}

	for _, invalid := range []string{
		`plain text`,
		`{"type":`,
		`{"type":"chat","content":123}`,
		`{"type":"unknown","content":"ignored"}`,
		`{"type":"chat","content":"  "}`,
	} {
		write(first, websocket.TextMessage, invalid)
	}
	write(first, websocket.BinaryMessage, `{"type":"chat","content":"binary ignored"}`)
	// 同一连接后发的有效消息应排在所有被忽略的消息之后。
	write(first, websocket.TextMessage, `{"type":"chat","content":"still working"}`)
	if msg := read(first, "still working"); msg.Sender != firstID {
		t.Fatalf("sender changed on the same connection: %q", msg.Sender)
	}
	read(second, "still working")
}
